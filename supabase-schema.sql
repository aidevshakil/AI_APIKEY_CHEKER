create table if not exists public.check_history (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default timezone('utc', now()),
  check_type text not null,
  provider_id text not null,
  provider_label text not null,
  base_url text not null,
  model text,
  api_key text not null,
  api_key_preview text not null,
  api_key_fingerprint text not null,
  valid boolean not null,
  usable_in_projects boolean,
  validation_status integer,
  validation_status_text text,
  models_found integer,
  sample_models text[] not null default '{}',
  remaining_usd numeric,
  estimated_tokens_left bigint,
  notes text,
  reply_preview text,
  raw_result jsonb not null
);

alter table public.check_history add column if not exists api_key text;
alter table public.check_history add column if not exists api_key_preview text;
alter table public.check_history add column if not exists api_key_fingerprint text;

create index if not exists check_history_created_at_idx on public.check_history (created_at desc);
create index if not exists check_history_api_key_fingerprint_idx on public.check_history (api_key_fingerprint);
